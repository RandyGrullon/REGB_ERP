create function pg_temp.tildes_0134(t text) returns text
language plpgsql
as $$
declare
  r record;
  s text := t;
begin
  if s is null or s = '' then
    return s;
  end if;
  for r in select patron, reemplazo from tildes_0134 order by orden loop
    s := regexp_replace(s, r.patron, r.reemplazo, 'g');
  end loop;
  return s;
end;
$$;

update regb.module_catalog mc
set
  name = pg_temp.tildes_0134(mc.name),
  description = pg_temp.tildes_0134(mc.description),
  tagline = pg_temp.tildes_0134(mc.tagline),
  problem = pg_temp.tildes_0134(mc.problem),
  audience = coalesce(
    (select array_agg(pg_temp.tildes_0134(a) order by i)
     from unnest(mc.audience) with ordinality as u(a, i)),
    mc.audience),
  -- `jsonb_strip_nulls` para no inventar claves que la ficha no tenia.
  features = coalesce(
    (select jsonb_agg(
              f || jsonb_strip_nulls(jsonb_build_object(
                     'titulo', pg_temp.tildes_0134(f->>'titulo'),
                     'detalle', pg_temp.tildes_0134(f->>'detalle')))
              order by i)
     from jsonb_array_elements(mc.features) with ordinality as e(f, i)),
    mc.features),
  faq = coalesce(
    (select jsonb_agg(
              f || jsonb_strip_nulls(jsonb_build_object(
                     'p', pg_temp.tildes_0134(f->>'p'),
                     'r', pg_temp.tildes_0134(f->>'r')))
              order by i)
     from jsonb_array_elements(mc.faq) with ordinality as e(f, i)),
    mc.faq),
  screens = coalesce(
    (select jsonb_agg(
              f || jsonb_strip_nulls(jsonb_build_object(
                     'titulo', pg_temp.tildes_0134(f->>'titulo'),
                     'descripcion', pg_temp.tildes_0134(f->>'descripcion')))
              order by i)
     from jsonb_array_elements(mc.screens) with ordinality as e(f, i)),
    mc.screens);

