-- ═══════════════════════════════════════════════════════════════════════
--  0134 — El catalogo del marketplace, con tildes y eñes
--
--  El texto visible de `regb.module_catalog` (nombre, descripcion, lema,
--  problema, que incluye, a quien le sirve, preguntas y los titulos de las
--  pantallas) se escribio sin tildes: "Nomina", "Conciliacion bancaria",
--  "Codigos de barra", "al ano". Es lo primero que lee un cliente que va a
--  pagar, y se lee descuidado. Lo que cambia es SOLO texto: ningun id,
--  categoria, precio ni dependencia.
--
--  ── Por que reglas y no el texto entero ──────────────────────────────
--
--  Otras migraciones corrigen fichas concretas (la 0116 la de impuestos,
--  la 0124 la de captura de facturas). Reescribir cada campo con su texto
--  final pisaria en silencio cualquier ficha que otra migracion cambie
--  antes que esta. Aqui se aplican reglas por palabra (`\m...\M`, limite de
--  palabra) sobre lo que haya, asi que una frase nueva sale corregida y
--  una ya corregida no se toca.
--
--  Tres grupos, en este orden:
--   1. Frases que deciden lo ambiguo: interrogativos ("sabe quien te debe"
--      -> "sabe quién te debe"), "está" frente a "esta version", "sí"
--      afirmativo, "tú" y "él" pronombres, y preteritos que tambien son
--      sustantivos ("quien lo cambio" -> "cambió", pero "tipo de cambio").
--   2. Palabras que siempre llevan tilde en este catalogo (módulo,
--      nómina, crédito, -ción...), en minuscula, Capitalizada y MAYUSCULA.
--   3. Reglas de contexto: "esta" -> "está" salvo delante de version/vez/
--      primera; "cuanto" -> "cuánto" salvo "en cuanto" (en cuanto pasa);
--      "Si," / "Si -" al responder -> "Sí".
--
--  Los esquemas de texto (`screens[].mockup`) NO se tocan: son dibujos de
--  pantalla en ASCII y su ancho cuenta.
-- ═══════════════════════════════════════════════════════════════════════

