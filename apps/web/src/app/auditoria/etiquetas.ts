function campoLegible(c: string): string {
  const partes = c.split('_')
  // "algo_at" se lee "algo el": es la fecha en que pasó.
  if (partes.length > 1 && partes[partes.length - 1] === 'at') {
    return `${partes
      .slice(0, -1)
      .map((p) => PALABRA[p] ?? p)
      .join(' ')} el`
  }
  // "algo_id" se lee "algo": el id no le dice nada a quien lee.
  const sinId =
    partes.length > 1 && partes[partes.length - 1] === 'id' ? partes.slice(0, -1) : partes
  return sinId.map((p) => PALABRA[p] ?? p).join(' ')
}

