const legible = (s: string) => s.replace(/[-_]/g, ' ')

/** Concuerda el participio con la cosa: "aprobado" → "aprobada" / "aprobadas". */
function concordar(paso: string, femenina: boolean, plural: boolean): string {
  if (INVARIABLES.has(paso) || (!femenina && !plural)) return paso
  const [primera = '', ...resto] = paso.split(' ')
  if (!/o$/.test(primera)) return paso
  const base = femenina ? `${primera.slice(0, -1)}a` : primera
  return [plural ? `${base}s` : base, ...resto].join(' ')
}

/** "helpdesk.ticket.resolved" → "Ticket resuelto"; "ar.invoice.paid" → "Factura pagada". */
export function nombreEvento(tipo: string): string {
  const partes = tipo.split('.')
  if (partes.length < 2) return legible(tipo)
  const paso = partes[partes.length - 1]!
  const cosa = partes.slice(1, -1).join('.') || partes[0]!
  const c = COSA[cosa] ?? legible(cosa)
  const p = concordar(PASO[paso] ?? legible(paso), FEMENINAS.has(cosa), PLURALES.has(cosa))
  return `${c.charAt(0).toUpperCase()}${c.slice(1)} ${p}`
}
